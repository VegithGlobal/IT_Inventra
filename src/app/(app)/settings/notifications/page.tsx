import type { Metadata } from "next";
import { Suspense } from "react";
import { Card, CardBody, CardHeader } from "@/components/ui/card";
import { PageHeader, PageSkeleton } from "@/components/ui/page";
import { EmailSettingsForm, ReminderDefaultsForm } from "@/features/notification-settings/views";
import { smtpSummary } from "@/lib/email";
import { requireUser } from "@/lib/session";
import { getEmailSettings, getReminderSettings } from "@/lib/settings";

export const metadata: Metadata = { title: "Notification settings" };

async function Content() {
  const user = await requireUser();
  const [reminders, email] = await Promise.all([getReminderSettings(), getEmailSettings()]);
  const readOnly = user.role !== "ADMIN";
  const base = (process.env.NEXTAUTH_URL ?? "http://localhost:3000").replace(/\/$/, "");
  return (
    <div className="flex flex-col gap-6">
      <PageHeader
        title="Notifications"
        description={readOnly ? "Only admins can change these settings." : "Reminder timing, email delivery and the scheduled job."}
      />
      <div className="grid grid-cols-1 gap-6 xl:grid-cols-2">
        <ReminderDefaultsForm
          readOnly={readOnly}
          initial={{
            subscriptionDaysBefore: reminders.subscriptionDaysBefore.join(", "),
            warrantyDaysBefore: String(reminders.warrantyDaysBefore),
            licenseDaysBefore: reminders.licenseDaysBefore.join(", "),
            ticketDueHoursBefore: String(reminders.ticketDueHoursBefore),
            assetReturnDaysBefore: String(reminders.assetReturnDaysBefore),
          }}
        />
        <EmailSettingsForm readOnly={readOnly} initial={email} smtp={smtpSummary()} />
      </div>
      <Card>
        <CardHeader title="Scheduled job" description="Reminders are generated by one endpoint. It's safe to run as often as you like — nothing is sent twice." />
        <CardBody className="flex flex-col gap-3 text-[13.5px] text-fg-secondary">
          <p>
            Endpoint: <code className="rounded bg-subtle px-1.5 py-0.5 text-[12.5px] text-fg">{base}/api/cron/reminders</code> with header{" "}
            <code className="rounded bg-subtle px-1.5 py-0.5 text-[12.5px] text-fg">Authorization: Bearer $CRON_SECRET</code>
            {process.env.CRON_SECRET ? null : <span className="ml-2 font-medium text-danger">CRON_SECRET is not set</span>}
          </p>
          <ul className="list-disc space-y-1 pl-5">
            <li>
              <span className="text-fg">Vercel:</span> <code className="text-[12.5px]">vercel.json</code> already schedules it daily at 08:00 IST.
            </li>
            <li>
              <span className="text-fg">Own server:</span> set <code className="text-[12.5px]">CRON_MODE=&quot;internal&quot;</code> to run it hourly inside the app, or call it from system cron.
            </li>
            <li>
              <span className="text-fg">Right now:</span> use “Run now” on the Reminders page.
            </li>
          </ul>
        </CardBody>
      </Card>
    </div>
  );
}

export default function NotificationSettingsPage() {
  return (
    <Suspense fallback={<PageSkeleton rows={6} />}>
      <Content />
    </Suspense>
  );
}
